// Мини-инструкция по файлу:
// Этот файл — набор утилит, которые использует локалайзер.
// Здесь есть функции для:
//  1) чтения JSON-файла из input (FileReader)
//  2) чтения ZIP-файла (JSZip)
//  3) получения значения перевода по пути "a.b.c"
//  4) получения baseName из пути файла ("assets/x/index.html" -> "index")
//  5) глубокого merge объектов переводов (base + page)
//  6) построения “пути элемента” в HTML для логов (selector-like строка)
//
// Важно: файл не содержит UI/логики архива целиком — это чистые помощники.
// ----------------------------------------------------------------------------

import JSZip from "jszip";


// ----------------------------------------------------------------------------
// readZipFile(file)
// ----------------------------------------------------------------------------
// Назначение:
//  - Прочитать ZIP (File/Blob) и вернуть загруженный объект JSZip,
//    чтобы дальше можно было делать zip.forEach(...) и file.async(...)
//
// Как работает:
//  - создаём экземпляр JSZip()
//  - вызываем loadAsync(file) — JSZip сам прочитает содержимое и построит структуру архива
//
// Возвращает:
//  - Promise с объектом zip (JSZip instance)
//
// Где используется:
//  - в основном пайплайне локалайзера при обработке архива.
// ----------------------------------------------------------------------------
function readZipFile(file) {
  const zip = new JSZip();
  return zip.loadAsync(file);
}

// ----------------------------------------------------------------------------
// readJsonFile(file)
// ----------------------------------------------------------------------------
// Назначение:
//  - Прочитать один JSON файл (объект File из input type="file") и вернуть распарсенный объект.
//
// Как работает:
//  - FileReader читает файл как текст в utf-8
//  - затем JSON.parse превращает строку в объект
//
// Возвращает:
//  - Promise, который resolve(obj) при успехе
//  - Promise, который reject(Error(...)) при ошибке чтения или парсинга
//
// Где используется:
//  - обычно когда пользователь загружает json отдельно (не zip), или для вспомогательных сценариев.
//
// Нюансы для новичков:
//  - reader.result здесь должен быть строкой; если файл не JSON или битый — JSON.parse упадёт.
//  - reject(new Error("...", e)) технически передаёт второй аргумент, но стандартный Error его не хранит;
//    полезная информация в логах чаще берётся из e.message.
// ----------------------------------------------------------------------------
function readJsonFile(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      try {
        const obj = JSON.parse(reader.result);
        resolve(obj);
      } catch (e) {
        reject(new Error("Не удалось распарсить JSON", e));
      }
    };
    reader.onerror = () => reject(new Error("Ошибка чтения JSON файла"));
    reader.readAsText(file, "utf-8");
  });
}


// ----------------------------------------------------------------------------
// propByPath(object, path)
// ----------------------------------------------------------------------------
// Назначение:
//  - Достать значение из объекта по “пути” вида "a.b.c".
//
// Пример:
//  const obj = { a: { b: { c: 123 } } }
//  propByPath(obj, "a.b.c") -> 123
//
// Как работает:
//  - path.split('.') превращает строку в массив ключей ["a","b","c"]
//  - reduce проходит по объекту шаг за шагом
//  - acc?.[cur] использует optional chaining:
//      если acc стал null/undefined — дальше не упадём, вернётся undefined.
//
// Нюанс:
//  - если в ключах реально встречаются точки (редко для переводов) — этот подход не подойдёт.
// ----------------------------------------------------------------------------
const propByPath = (object, path) => path.split(".").reduce((acc, cur) => acc?.[cur], object);

// ----------------------------------------------------------------------------
// getTranslationValue(translations, key)
// ----------------------------------------------------------------------------
// Назначение:
//  - Вернуть перевод по ключу (key) из объекта translations.
//  - key может быть вложенным путём (через точки), например "header.title".
//
// Возвращает:
//  - значение перевода (любой тип: строка/число/объект) или null, если не найдено.
//
// Почему возвращает null, а не undefined:
//  - дальше в коде удобно проверять "value != null" для “есть перевод / нет перевода”
//
// Как работает:
//  - проверяет, что key и translations существуют
//  - использует propByPath, чтобы достать значение по пути
//  - value ?? null превращает undefined в null, но сохраняет 0/false/"" как валидные значения.
//
// Важно для новичков:
//  - если перевод — пустая строка "" — она НЕ станет null (это корректное значение).
// ----------------------------------------------------------------------------
function getTranslationValue(translations, key) {
  if (!key) return null;
  const root = translations;
  if (!root) return null;

  const value = propByPath(root, key);
  return value ?? null;
}

// ----------------------------------------------------------------------------
// getBaseName(path)
// ----------------------------------------------------------------------------
// Назначение:
//  - Получить “базовое имя” файла без расширения из полного пути.
//
// Примеры:
//  getBaseName("assets/locales/base.json") -> "base"
//  getBaseName("index.html")              -> "index"
//  getBaseName("a/b/c/page.en.html")      -> "page.en"  (удаляется только последнее расширение)
//
// Как работает:
//  - path.split(/[\\/]/) делит и по "/" и по "\" (поддержка разных форм путей)
//  - .pop() берёт последнее (имя файла)
//  - replace(/\.[^.]+$/, "") убирает последнюю точку + расширение
//
// Важно:
//  - используется для сопоставления HTML и JSON:
//      "<name>.html" <-> "assets/locales/<name>.json"
// ----------------------------------------------------------------------------
function getBaseName(path) {
  const fileName = path.split(/[\\/]/).pop() || "";
  return fileName.replace(/\.[^.]+$/, "");
}




// ----------------------------------------------------------------------------
// getElementPath(el)
// ----------------------------------------------------------------------------
// Назначение:
//  - Построить строку “похожую на CSS-путь”, чтобы в логах можно было быстро найти элемент.
//
// Пример результата:
//  "body.main > section.hero > h1.title"
//  или "div#app" (если встретили id — на нём останавливаемся)
//
// Как строится:
//  - идём от элемента вверх по parentElement до <html>
//  - на каждом шаге добавляем:
//      * tagName (например "div")
//      * если есть id → добавляем "#id" и прекращаем подъём (id обычно уникален)
//      * иначе, если есть классы → добавляем первые 1-2 класса (для читабельности)
//  - собираем части в " > "
//
// Почему берём максимум 2 класса:
//  - чтобы путь не превращался в километровую простыню.
//
// Возвращает:
//  - строку пути или "unknown", если не смогли собрать.
// ----------------------------------------------------------------------------
function getElementPath(el) {
  const parts = [];

  while (el && el.nodeType === 1 && el.tagName.toLowerCase() !== "html") {
    let part = el.tagName.toLowerCase();

    if (el.id) {
      part += `#${el.id}`;
      parts.unshift(part);
      break;
    }

    if (el.classList && el.classList.length) {
      part += "." + Array.from(el.classList).slice(0, 2).join(".");
    }

    parts.unshift(part);
    el = el.parentElement;
  }

  return parts.join(" > ") || "unknown";
}


function hasTranslatableLetters(input) {
  if (input == null) return false;

  let s = String(input);
  if (s.trim() === "") return false;

  // если похоже на HTML — проверяем только видимый текст (классы/теги игнор)
  if (/<[^>]*>/.test(s)) {
    // вырезаем комменты, теги, и entity типа &nbsp;
    s = s
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/<[^>]*>/g, "")
      .replace(/&(?:#\d+|#x[0-9a-fA-F]+|[A-Za-z][A-Za-z0-9]+);/g, "");
    if (s.trim() === "") return false;
  }

  // Unicode-буквы (кириллица, латиница, иероглифы и т.д.)
  try {
    return /\p{L}/u.test(s);
  } catch {
    // очень старый runtime: минимальный фолбэк
    return /[A-Za-zА-Яа-яЁё]/.test(s);
  }
}
